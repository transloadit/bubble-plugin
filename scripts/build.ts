import { mkdir, readFile, writeFile } from 'node:fs/promises'

import { build } from 'esbuild'

// Uppy 6.0.5 ships the exact core/dashboard/transloadit versions in package.json.
// The versioned Transloadit CDN is a trusted runtime dependency; keep its pin and typed API in sync.
const cdn = 'https://releases.transloadit.com/uppy/v6.0.5/uppy.min'
const modules: Record<string, [string, string]> = {
  '@uppy/core': ['Uppy', '6.3.0'],
  '@uppy/dashboard': ['Dashboard', '6.0.2'],
  '@uppy/transloadit': ['Transloadit', '6.0.1'],
}
const { dependencies }: { dependencies: Record<string, string> } = JSON.parse(
  await readFile('package.json', 'utf8'),
)
for (const [name, [, version]] of Object.entries(modules)) {
  if (dependencies[name] !== version)
    throw new Error(`Update the official Uppy CDN release alongside ${name}`)
}
const { outputFiles } = await build({
  entryPoints: ['src/uploader.ts'],
  bundle: true,
  write: false,
  minify: true,
  target: 'es2022',
  format: 'iife',
  globalName: 'TransloaditBubble',
  plugins: [
    {
      name: 'official-uppy-cdn',
      setup(build) {
        build.onResolve({ filter: /^@uppy\// }, ({ path }) => ({ path, namespace: 'uppy' }))
        build.onLoad({ filter: /.*/, namespace: 'uppy' }, ({ path }) => ({
          contents: `export default vendor.${modules[path][0]}`,
        }))
      },
    },
  ],
})
await writeFile(
  'html_headers.html',
  `<link rel="stylesheet" href="${cdn}.css">\n<script>\n// Generated by yarn build from src/uploader.ts.\nwindow.TransloaditBubbleReady = import('${cdn}.mjs').then(function(vendor) {\n${outputFiles[0].text}\nreturn TransloaditBubble;\n});\nwindow.TransloaditBubbleReady.catch(function() {});\n</script>\n`,
)
await mkdir('elements/AAu', { recursive: true })
for (const method of ['initialize', 'update', 'reset']) {
  const args = method === 'update' ? 'instance, properties, context' : 'instance, context'
  const ready = method === 'initialize' ? 'window.TransloaditBubbleReady' : 'instance.data.ready'
  const call =
    method === 'initialize' ? `api.${method}(${args}); return api;` : `api.${method}(${args});`
  const start =
    method === 'initialize'
      ? 'instance.data.initializationFailed = false;\n  instance.data.ready = '
      : ''
  const failure =
    method === 'initialize'
      ? 'instance.data.initializationFailed = true;'
      : 'if (instance.data.initializationFailed) return;'
  await writeFile(
    `elements/AAu/${method}.js`,
    `function(${args}) {\n  // Generated by yarn build.\n  ${start}${ready}.then(function(api) { ${call} })${method === 'initialize' ? ';\n  instance.data.ready' : ''}.catch(function(error) {\n    ${failure}\n    instance.publishState('error_message', error.message);\n    instance.triggerEvent('error');\n  });\n}\n`,
  )
}
await writeFile(
  'actions/AAF/client.js',
  `function(properties, context) {\n  // Generated by yarn build.\n  window.TransloaditBubbleReady.then(function(api) { api.open(properties, context); })\n    .catch(function(error) { context.reportDebugger(error.message); });\n}\n`,
)
